# Workspace cleanup detection for MnemoCetus (v0.5 Stage B - MnemoClean's detect-and-measure half).
#
# The scan filters regenerable bloat (RECLAIMABLE_MARKERS) out of a project; this module still SIZES those dirs so we can tell the user how much disk is reclaimable.
# Detection only: it never deletes anything (the recommendations layer lives in db_manager.cleanup_recommendations).

import os
import stat

from scanner import _is_excluded  # reuse the scan's exclusion test, so "excluded but not reclaimable" (e.g. .git) is handled identically

# Directories the scan filters out but that we still want to SIZE, because they're regenerable: delete them and a tool rebuilds them. 
# Each entry: dir name -> (kind, how it comes back).
# This is deliberately a curated set (not the whole exclude list) -> things like .git are excluded from scans too, but they are NOT reclaimable, so they must never show up as a "mark".
RECLAIMABLE_MARKERS = {
    "node_modules":   ("dependencies", "npm / yarn / pnpm install"),
    "vendor":         ("dependencies", "go mod / composer install"),
    "venv":           ("virtualenv", "python -m venv"),
    ".venv":          ("virtualenv", "python -m venv"),
    "__pycache__":    ("cache", "regenerated by Python"),
    ".pytest_cache":  ("cache", "regenerated by pytest"),
    ".mypy_cache":    ("cache", "regenerated by mypy"),
    ".ruff_cache":    ("cache", "regenerated by ruff"),
    ".tox":           ("cache", "regenerated by tox"),
    ".gradle":        ("cache", "regenerated by Gradle"),
    ".cache":         ("cache", "rebuildable cache"),
    "target":         ("build", "cargo / maven build"),
    "dist":           ("build", "build output"),
    "build":          ("build", "build output"),
    ".next":          ("build", "next build"),
    ".nuxt":          ("build", "nuxt build"),
    ".svelte-kit":    ("build", "svelte-kit build"),
}

def _dir_size(path):
    """
    (size_bytes, file_count) of a directory subtree -> a 'du' used to weigh a mark.

    size_bytes is what DELETING the tree would actually free, which a naive sum overstates:
      - symlinks are never followed (their target lives elsewhere; deleting the link frees nothing)
      - a hard-linked file only counts once ALL of its links are inside this tree. pnpm's node_modules
        hard-links every file to a global store, so deleting it frees ~nothing -> it must not show as GBs.
    file_count still counts every regular file entry.
    """
    if os.path.islink(path):
        return 0, 0
    total_bytes = total_files = 0
    links_seen = {}  # (st_dev, st_ino) -> how many of this inode's links we've met inside the tree
    for root, _dirs, files in os.walk(path):  # followlinks=False -> symlinked sub-dirs aren't descended
        for f in files:
            try:
                st = os.lstat(os.path.join(root, f))
            except OSError:
                continue
            if stat.S_ISLNK(st.st_mode) or not stat.S_ISREG(st.st_mode):
                continue
            total_files += 1
            if st.st_nlink <= 1:
                total_bytes += st.st_size
                continue
            key = (st.st_dev, st.st_ino)
            links_seen[key] = links_seen.get(key, 0) + 1
            if links_seen[key] == st.st_nlink:  # every link is in here -> deleting frees the data
                total_bytes += st.st_size
    return total_bytes, total_files

def _collect_marks(directory, name_rules, path_rules, skip=()):
    """
    Walk the given 'directory' and flag every regenerable/bloat subtree (as seen in RECLAIMABLE_MARKERS) that the normal scan filters out, additionally sizing each one so we can tell the user how much disk is reclaimable.

    A reclaimable dir is measured whole (we 'du' it) and then NOT descended into.
    Other excluded or hidden dirs are skipped just like the scan skips them -> but they're not marks, so they aren't sized.

    Args:
        directory (str): the project dir to inspect.
        name_rules (set): compiled basename exclude rules (to skip non-reclaimable excluded dirs).
        path_rules (set): compiled path exclude rules.
        skip (iterable): directories NOT to descend into -> the nested child projects, which collect
            their own marks (otherwise a parent re-counts every child's node_modules / venv).

    Returns:
        list[dict]: one {kind, name, path, size_bytes, file_count, reason} per reclaimable dir found.
    """
    skip = {os.path.normpath(p) for p in skip}
    marks = []
    for root, dirs, files in os.walk(directory):
        keep = []
        for d in dirs:
            full = os.path.join(root, d)
            if skip and os.path.normpath(full) in skip:
                continue  # a nested project -> it reports its own marks
            if os.path.islink(full):
                continue  # a symlinked 'venv' points elsewhere -> not reclaimable here (the Reclaimer refuses it too)
            marker = RECLAIMABLE_MARKERS.get(d)
            if marker:
                kind, reason = marker
                size, count = _dir_size(full)
                marks.append({
                    "kind": kind, "name": d, "path": os.path.normpath(full),
                    "size_bytes": size, "file_count": count, "reason": reason,
                })
                continue  # measured the whole subtree -> don't descend into it
            if d.startswith('.') or _is_excluded(full, name_rules, path_rules):
                continue  # excluded/hidden but not reclaimable (e.g. .git) -> skip, don't mark
            keep.append(d)
        dirs[:] = keep
    return marks
