# Shell integration for `nemc init <shell>` -> the prompt status light + tab-completion, in one eval line:
#
#   bash:  eval "$(nemc init bash)"        (~/.bashrc)
#   zsh:   eval "$(nemc init zsh)"         (~/.zshrc)
#   fish:  nemc init fish | source         (~/.config/fish/config.fish)
#
# The completion scripts are GENERATED from the argparse parser, so they can never drift from the real
# commands / options. The prompt hook calls `nemc status --prompt`, which prints a coloured dot (or nothing)
# and is guaranteed silent + time-boxed.

import argparse

SHELLS = ("bash", "zsh", "fish")

# Value completion for options that take an argument (by argparse dest).
_FILE_DESTS = {"db", "output"}
_DIR_DESTS = {"under"}
_KNOWN_VALUES = {"kind": ["dependencies", "virtualenv", "cache", "build"]}  # reclaim --kind (open-ended in argparse)


def _spec(parser):
    """
    Flatten the parser -> {"global": opts, "commands": {name: {"help", "opts", "positional_dir"}}} where
    opts is a list of {"flags": [...], "takes_value": bool, "values": [...] | None, "kind": file|dir|None, "help"}.
    """
    def opts_of(p):
        out = []
        for a in p._actions:
            if not a.option_strings or isinstance(a, argparse._SubParsersAction):
                continue
            takes = a.nargs != 0 and not isinstance(a, (argparse._StoreTrueAction, argparse._StoreFalseAction,
                                                        argparse._HelpAction, argparse._VersionAction))
            values = list(a.choices) if a.choices else _KNOWN_VALUES.get(a.dest)
            kind = "file" if a.dest in _FILE_DESTS else "dir" if a.dest in _DIR_DESTS else None
            out.append({"flags": list(a.option_strings), "takes_value": takes, "values": values, "kind": kind,
                        "help": (a.help or "").replace("%%", "%")})
        return out

    spec = {"global": opts_of(parser), "commands": {}}
    for a in parser._actions:
        if isinstance(a, argparse._SubParsersAction):
            helps = {c.dest: c.help for c in a._choices_actions}
            for name, sub in a.choices.items():
                positionals = [x for x in sub._actions if not x.option_strings]
                spec["commands"][name] = {"help": helps.get(name, ""), "opts": opts_of(sub),
                                          "positional_dir": bool(positionals)}
    return spec


def _value_options(spec):
    """Every option that takes a value, across global + all commands -> {flag: (values, kind)}."""
    out = {}
    for o in spec["global"] + [o for c in spec["commands"].values() for o in c["opts"]]:
        if o["takes_value"]:
            for f in o["flags"]:
                out.setdefault(f, (o["values"], o["kind"]))
    return out


# --------------------------------------------------------------------------- #
# Completion scripts
# --------------------------------------------------------------------------- #
def bash_completion(parser):
    spec = _spec(parser)
    cmds = " ".join(spec["commands"])
    global_flags = " ".join(f for o in spec["global"] for f in o["flags"])
    value_cases = []
    for flag, (values, kind) in sorted(_value_options(spec).items()):
        if values:
            body = f'COMPREPLY=($(compgen -W "{" ".join(values)}" -- "$cur"))'
        elif kind == "file":
            body = 'COMPREPLY=($(compgen -f -- "$cur"))'
        elif kind == "dir":
            body = 'COMPREPLY=($(compgen -d -- "$cur"))'
        else:
            body = "COMPREPLY=()"
        value_cases.append(f"        {flag}) {body}; return ;;")
    cmd_cases = []
    for name, c in spec["commands"].items():
        flags = " ".join(f for o in c["opts"] for f in o["flags"])
        cmd_cases.append(f'        {name}) opts="{flags}"; posdir={1 if c["positional_dir"] else 0} ;;')
    global_skip = "|".join(f for o in spec["global"] if o["takes_value"] for f in o["flags"]) or "--db"
    return f"""# nemc bash completion (generated by `nemc init bash`)
_nemc_complete() {{
    local cur="${{COMP_WORDS[COMP_CWORD]}}" prev="${{COMP_WORDS[COMP_CWORD-1]}}"
    local i cmd="" opts="" posdir=0
    for ((i = 1; i < COMP_CWORD; i++)); do
        case "${{COMP_WORDS[i]}}" in
            {global_skip}) ((i++)) ;;
            -*) ;;
            *) cmd="${{COMP_WORDS[i]}}"; break ;;
        esac
    done
    case "$prev" in
{chr(10).join(value_cases)}
    esac
    if [[ -z "$cmd" ]]; then
        COMPREPLY=($(compgen -W "{cmds} {global_flags}" -- "$cur"))
        return
    fi
    case "$cmd" in
{chr(10).join(cmd_cases)}
    esac
    if [[ "$cur" == -* ]]; then
        COMPREPLY=($(compgen -W "$opts" -- "$cur"))
    elif ((posdir)); then
        COMPREPLY=($(compgen -d -- "$cur"))
    else
        COMPREPLY=()
    fi
}}
complete -o filenames -o bashdefault -F _nemc_complete nemc
"""


def zsh_completion(parser):
    # zsh runs the generated bash completion through its bashcompinit bridge -> one source of truth.
    return f"""# nemc zsh completion (generated by `nemc init zsh`; uses zsh's bash-completion bridge)
autoload -Uz compinit bashcompinit
(( $+functions[compdef] )) || compinit -u
bashcompinit
{bash_completion(parser)}"""


def _fish_quote(text):
    return "'" + str(text).replace("\\", "\\\\").replace("'", "\\'") + "'"


def fish_completion(parser):
    spec = _spec(parser)
    lines = ["# nemc fish completion (generated by `nemc init fish`)", "complete -c nemc -f"]

    def opt_line(o, cond):
        parts = ["complete -c nemc", f"-n {_fish_quote(cond)}"]
        for f in o["flags"]:
            parts.append(f"-l {f[2:]}" if f.startswith("--") else f"-s {f[1:]}")
        if o["takes_value"]:
            parts.append("-r")
            if o["values"]:
                parts.append(f"-a {_fish_quote(' '.join(o['values']))}")
            elif o["kind"] in ("file", "dir"):
                parts.append("-F")
        if o["help"]:
            parts.append(f"-d {_fish_quote(o['help'][:80])}")
        return " ".join(parts)

    for o in spec["global"]:
        lines.append(opt_line(o, "__fish_use_subcommand"))
    for name, c in spec["commands"].items():
        lines.append(f"complete -c nemc -n '__fish_use_subcommand' -a {name} -d {_fish_quote(c['help'])}")
        cond = f"__fish_seen_subcommand_from {name}"
        for o in c["opts"]:
            lines.append(opt_line(o, cond))
        if c["positional_dir"]:
            lines.append(f"complete -c nemc -n {_fish_quote(cond)} -a '(__fish_complete_directories)'")
    return "\n".join(lines) + "\n"


# --------------------------------------------------------------------------- #
# Prompt hooks
# --------------------------------------------------------------------------- #
BASH_PROMPT = r"""# nemc status light (generated by `nemc init bash`): a coloured dot before your prompt when you're
# inside a scanned project -> green up to date, amber changed since last scan, red security findings.
__nemc_light() {
    local s
    s="$(command nemc status --prompt --shell bash 2>/dev/null)"
    [[ -n "$s" ]] && printf '%s ' "$s"
}
case "$PS1" in
    *__nemc_light*) ;;
    *) PS1='$(__nemc_light)'"$PS1" ;;
esac
"""

ZSH_PROMPT = r"""# nemc status light (generated by `nemc init zsh`): a coloured dot before your prompt when you're
# inside a scanned project -> green up to date, amber changed since last scan, red security findings.
setopt PROMPT_SUBST
autoload -Uz add-zsh-hook
__nemc_precmd() {
    __NEMC_LIGHT="$(command nemc status --prompt --shell zsh 2>/dev/null)"
    [[ -n "$__NEMC_LIGHT" ]] && __NEMC_LIGHT+=" "
}
add-zsh-hook precmd __nemc_precmd
[[ "$PROMPT" == *'${__NEMC_LIGHT}'* ]] || PROMPT='${__NEMC_LIGHT}'"$PROMPT"
"""

FISH_PROMPT = r"""# nemc status light (generated by `nemc init fish`): a coloured dot before your prompt when you're
# inside a scanned project -> green up to date, amber changed since last scan, red security findings.
function __nemc_light
    set -l s (command nemc status --prompt --shell fish 2>/dev/null)
    test -n "$s"; and printf '%s ' $s
end
if functions -q fish_prompt; and not functions -q __nemc_orig_fish_prompt
    functions -c fish_prompt __nemc_orig_fish_prompt
    function fish_prompt
        __nemc_light
        __nemc_orig_fish_prompt
    end
end
"""


def init_script(shell, parser, prompt=True, completion=True):
    """The text `nemc init <shell>` prints: the prompt hook and/or the completion script."""
    if shell not in SHELLS:
        raise ValueError(f"unsupported shell: {shell}")
    parts = []
    if prompt:
        parts.append({"bash": BASH_PROMPT, "zsh": ZSH_PROMPT, "fish": FISH_PROMPT}[shell])
    if completion:
        parts.append({"bash": bash_completion, "zsh": zsh_completion, "fish": fish_completion}[shell](parser))
    return "\n".join(parts)
